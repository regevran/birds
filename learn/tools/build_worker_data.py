#!/usr/bin/env python3
"""Bundle the shared dataset into the Worker as a generated ES module.

The Worker needs the same species and etymology records as the Python
clients. Wrangler cannot read `data/out` from outside its bundle root, so this
script writes a generated module under `learn/cloudflare/src/generated/`.
That directory is gitignored; CMake regenerates it before Worker tests and
deploys.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "out"
TARGET = ROOT / "learn" / "cloudflare" / "src" / "generated" / "data.js"


def data_version(species: object, etymology: object) -> str:
    payload = json.dumps(
        [species, etymology],
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return f"sha256:{digest}"


def main() -> int:
    species = json.loads(
        (DATA / "israel_birds_final.json").read_text(encoding="utf-8")
    )
    etymology = json.loads(
        (DATA / "etymology.json").read_text(encoding="utf-8")
    )
    version = data_version(species, etymology)

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "// Generated by learn/tools/build_worker_data.py; do not edit.\n"
        f"export const dataVersion = {json.dumps(version)};\n"
        "export const species = "
        f"{json.dumps(species, ensure_ascii=False, separators=(',', ':'))};\n"
        "export const etymology = "
        f"{json.dumps(etymology, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    TARGET.write_text(text, encoding="utf-8")
    print(f"Wrote {TARGET} ({len(text)} bytes, {version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
